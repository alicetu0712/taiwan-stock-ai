from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import List


class BlockerCategory(str, Enum):
    A = "A_immediate_fix"       # Research-only code/logic fix, no data changes
    B = "B_existing_data"       # Can improve by reorganising existing data
    C = "C_external_data"       # Needs external data (listing dates, delistings, etc.)
    D = "D_requires_auth"       # Needs production migration or Cron authorisation


class BlockerSeverity(str, Enum):
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class BlockerStatus(str, Enum):
    RESOLVED = "RESOLVED"
    PARTIAL = "PARTIAL_RESOLUTION"
    OPEN = "OPEN"


@dataclass(frozen=True)
class BlockerEntry:
    check_id: str                       # e.g. "EG-02"
    check_name: str
    category: BlockerCategory
    severity: BlockerSeverity
    actual_value: str
    required_condition: str
    evidence_source: str
    affected_date_range: str
    affected_signal_count: int
    affected_stock_count: int
    root_cause: str
    remediation: str
    required_permission: str            # "none" / "read-only" / "db-write" / "cron-auth"
    estimated_effort: str
    current_status: BlockerStatus
    resolution_note: str = ""


@dataclass
class ResearchBlockerMatrix:
    """
    Classified breakdown of all research blockers from EligibilityGate + ComparabilityReport.

    Categories:
      A — Can fix immediately with research-only code or analysis logic.
      B — Can improve using existing data (no new data needed).
      C — Needs external data not currently in the platform.
      D — Needs production changes or authorisation not yet granted.
    """
    blockers: List[BlockerEntry] = field(default_factory=list)

    def category(self, cat: BlockerCategory) -> List[BlockerEntry]:
        return [b for b in self.blockers if b.category == cat]

    def open_blockers(self) -> List[BlockerEntry]:
        return [b for b in self.blockers if b.current_status == BlockerStatus.OPEN]

    def critical_open(self) -> List[BlockerEntry]:
        return [b for b in self.open_blockers() if b.severity == BlockerSeverity.CRITICAL]

    def summary(self) -> dict:
        total = len(self.blockers)
        resolved = sum(1 for b in self.blockers if b.current_status == BlockerStatus.RESOLVED)
        partial = sum(1 for b in self.blockers if b.current_status == BlockerStatus.PARTIAL)
        open_b = sum(1 for b in self.blockers if b.current_status == BlockerStatus.OPEN)
        return {
            "total": total,
            "resolved": resolved,
            "partial": partial,
            "open": open_b,
            "by_category": {
                "A": len(self.category(BlockerCategory.A)),
                "B": len(self.category(BlockerCategory.B)),
                "C": len(self.category(BlockerCategory.C)),
                "D": len(self.category(BlockerCategory.D)),
            },
        }


