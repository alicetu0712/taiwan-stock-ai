"""
eligible_window_discovery.py — Find minimum viable eligible windows for strategy comparison.

RESEARCH ONLY. Read-only. No production DB writes.

Window discovery logic:
  1. Enumerate candidate windows from forward_signals dates.
  2. Check each window against 10 research eligibility criteria.
  3. Report pass/fail/conditional for each criterion.
  4. Output comparison eligibility verdict and exclusion reasons.

Selection-bias prevention:
  Windows are assessed on DATA QUALITY criteria before any performance is computed.
  Performance is NEVER used to select windows.
"""
from __future__ import annotations

import sqlite3
from dataclasses import dataclass, field
from enum import Enum
from typing import List, Optional


class WindowVerdict(str, Enum):
    ELIGIBLE = "ELIGIBLE"
    CONDITIONAL = "CONDITIONAL"
    INELIGIBLE = "INELIGIBLE"


class CheckVerdict(str, Enum):
    PASS = "PASS"
    CONDITIONAL = "CONDITIONAL"
    FAIL = "FAIL"
    SKIP = "SKIP"


@dataclass(frozen=True)
class WindowCheck:
    check_id: str
    check_name: str
    verdict: CheckVerdict
    actual: str
    required: str
    note: str = ""


@dataclass
class CandidateWindow:
    """
    One candidate research window.

    Fields are set from data, not from performance.
    """
    window_id: str
    start_date: str
    end_date: str
    horizon_days: int
    eligible_stock_count: int
    eligible_signal_count: int
    paired_sample_count: int              # signals with actual outcome data
    missing_outcome_count: int
    universe_description: str
    checks: List[WindowCheck] = field(default_factory=list)
    comparison_eligibility: WindowVerdict = WindowVerdict.INELIGIBLE
    exclusion_reasons: List[str] = field(default_factory=list)
    n_independent_dates: int = 0
    effective_n_estimate: int = 0
    benchmark_available: bool = False
    regime_coverage: str = ""             # e.g. "bull_only" / "mixed"

    def n_failed_checks(self) -> int:
        return sum(1 for c in self.checks if c.verdict == CheckVerdict.FAIL)

    def n_conditional_checks(self) -> int:
        return sum(1 for c in self.checks if c.verdict == CheckVerdict.CONDITIONAL)

    def n_passed_checks(self) -> int:
        return sum(1 for c in self.checks if c.verdict == CheckVerdict.PASS)


@dataclass
class EligibleWindowDiscovery:
    """Result of window discovery scan."""
    candidate_windows: List[CandidateWindow] = field(default_factory=list)
    best_window_id: Optional[str] = None
    overall_verdict: str = "NO_ELIGIBLE_WINDOW"

    def eligible(self) -> List[CandidateWindow]:
        return [w for w in self.candidate_windows
                if w.comparison_eligibility == WindowVerdict.ELIGIBLE]

    def conditional(self) -> List[CandidateWindow]:
        return [w for w in self.candidate_windows
                if w.comparison_eligibility == WindowVerdict.CONDITIONAL]


def _assess_window(
    conn: sqlite3.Connection,
    signal_dates: List[str],
    horizon: int,
) -> CandidateWindow:
    """Assess a candidate window on 10 research criteria."""
    if not signal_dates:
        return CandidateWindow(
            window_id=f"empty_{horizon}d",
            start_date="N/A", end_date="N/A",
            horizon_days=horizon,
            eligible_stock_count=0, eligible_signal_count=0,
            paired_sample_count=0, missing_outcome_count=0,
            universe_description="empty",
            comparison_eligibility=WindowVerdict.INELIGIBLE,
            exclusion_reasons=["No signal dates provided"],
        )

    start = signal_dates[0]
    end = signal_dates[-1]
    window_id = f"{'_'.join([d.replace('-', '') for d in [start, end]])}_{horizon}d"
    checks: List[WindowCheck] = []
    exclusion: List[str] = []

    # ── C1: Official security classification ──────────────────────────────────
    # All v8.0 signals officially classified (Session 38)
    checks.append(WindowCheck(
        check_id="C1",
        check_name="Official security classification",
        verdict=CheckVerdict.PASS,
        actual="100% of v8.0 signals officially classified (Session 38)",
        required="All signals classified as TWSE/TPEx common or ETF",
        note="Dataset B (2023 signals) uses official TWSE/TPEx classification",
    ))

    # ── C2: Point-in-time universe ────────────────────────────────────────────
    # For forward_signals (production-generated), de facto point-in-time
    checks.append(WindowCheck(
        check_id="C2",
        check_name="Point-in-time universe",
        verdict=CheckVerdict.CONDITIONAL,
        actual=(
            "forward_signals generated by live production system → stocks present in "
            "master at signal time. No listing_date column to verify formally."
        ),
        required="Stocks must have been listed on signal_date",
        note="De facto point-in-time for forward_signals. Formal listing_date verification missing.",
    ))

    # ── C3: Trading date validity ──────────────────────────────────────────────
    # Check all signal dates exist in daily_prices
    cur = conn.cursor()
    date_placeholders = ",".join(["?" for _ in signal_dates])
    cur.execute(
        f"SELECT COUNT(DISTINCT date) FROM daily_prices WHERE date IN ({date_placeholders})",
        signal_dates,
    )
    n_valid_dates = cur.fetchone()[0]
    c3_pass = n_valid_dates == len(signal_dates)
    checks.append(WindowCheck(
        check_id="C3",
        check_name="Trading date validity",
        verdict=CheckVerdict.PASS if c3_pass else CheckVerdict.FAIL,
        actual=f"{n_valid_dates}/{len(signal_dates)} dates in daily_prices",
        required="All signal dates must exist in daily_prices",
    ))
    if not c3_pass:
        exclusion.append(f"C3: {len(signal_dates) - n_valid_dates} signal dates missing from daily_prices")

    # ── C4: Market data coverage ──────────────────────────────────────────────
    # Check post-bars per signal
    cur.execute(
        f"""
        SELECT COUNT(*) as total,
               SUM(CASE WHEN post_bars >= ? THEN 1 ELSE 0 END) as eligible
        FROM (
            SELECT fs.stock_id, fs.trade_date,
                   (SELECT COUNT(*) FROM daily_prices dp
                    WHERE dp.stock_id = fs.stock_id AND dp.date > fs.trade_date) as post_bars
            FROM forward_signals fs
            WHERE fs.trade_signal IN ('buy','strong_buy')
            AND fs.trade_date IN ({date_placeholders})
        )
        """,
        [horizon] + signal_dates,
    )
    row = cur.fetchone()
    total_sigs, eligible_sigs = row
    coverage_pct = eligible_sigs / total_sigs * 100 if total_sigs > 0 else 0
    c4_verdict = (
        CheckVerdict.PASS if coverage_pct >= 80
        else CheckVerdict.CONDITIONAL if coverage_pct >= 50
        else CheckVerdict.FAIL
    )
    checks.append(WindowCheck(
        check_id="C4",
        check_name="Market data coverage",
        verdict=c4_verdict,
        actual=f"{eligible_sigs}/{total_sigs} signals ({coverage_pct:.1f}%) have ≥{horizon}D post-bars",
        required="≥80% of signals must have ≥horizon post-bars",
        note="daily_prices last date: 2026-11-05",
    ))
    if c4_verdict == CheckVerdict.FAIL:
        exclusion.append(f"C4: Only {coverage_pct:.1f}% coverage for {horizon}D horizon")

    # ── C5: Benchmark availability ────────────────────────────────────────────
    cur.execute(
        f"SELECT COUNT(*) FROM daily_prices WHERE stock_id = '0050' AND date IN ({date_placeholders})",
        signal_dates,
    )
    n_bench = cur.fetchone()[0]
    bench_ok = n_bench == len(signal_dates)
    checks.append(WindowCheck(
        check_id="C5",
        check_name="Benchmark availability (0050)",
        verdict=CheckVerdict.PASS if bench_ok else CheckVerdict.CONDITIONAL,
        actual=f"0050 available for {n_bench}/{len(signal_dates)} signal dates",
        required="0050 prices available for all signal dates",
    ))

    # ── C6: Price freshness ───────────────────────────────────────────────────
    # source_price_date in forward_signals
    cur.execute(
        f"""
        SELECT COUNT(*) as total,
               SUM(CASE WHEN source_price_date IS NOT NULL THEN 1 ELSE 0 END) as fresh
        FROM forward_signals
        WHERE trade_date IN ({date_placeholders})
        AND is_valid=1 AND model_version='v8.0'
        """,
        signal_dates,
    )
    row = cur.fetchone()
    total_v, fresh_v = row
    fresh_pct = fresh_v / total_v * 100 if total_v > 0 else 0
    checks.append(WindowCheck(
        check_id="C6",
        check_name="Price freshness (source_price_date)",
        verdict=CheckVerdict.CONDITIONAL,
        actual=f"{fresh_v}/{total_v} ({fresh_pct:.0f}%) signals have source_price_date",
        required="source_price_date populated and ≤1 day before signal_date",
        note="Population rate known; staleness threshold not formally verified",
    ))

    # ── C7: Corporate action adjustment ──────────────────────────────────────
    checks.append(WindowCheck(
        check_id="C7",
        check_name="Corporate action adjustment",
        verdict=CheckVerdict.CONDITIONAL,
        actual="Adjustment status not documented in daily_prices schema",
        required="Prices adjusted for splits and rights issues",
        note="Assumed adjusted (standard for data vendors); unverified",
    ))

    # ── C8: Missing outcomes ──────────────────────────────────────────────────
    # Check forward_signals.fwd_return_Xd or use daily_prices for computation
    cur.execute(
        f"""
        SELECT COUNT(*) as total,
               SUM(CASE WHEN post_bars >= ? THEN 1 ELSE 0 END) as has_outcome
        FROM (
            SELECT fs.stock_id, fs.trade_date,
                   (SELECT COUNT(*) FROM daily_prices dp
                    WHERE dp.stock_id = fs.stock_id AND dp.date > fs.trade_date) as post_bars
            FROM forward_signals fs
            WHERE fs.trade_signal IN ('buy','strong_buy')
            AND fs.trade_date IN ({date_placeholders})
        )
        """,
        [horizon] + signal_dates,
    )
    row = cur.fetchone()
    total_o, has_outcome = row
    missing_o = total_o - has_outcome
    c8_verdict = CheckVerdict.PASS if missing_o == 0 else (
        CheckVerdict.CONDITIONAL if has_outcome > 0 else CheckVerdict.FAIL
    )
    checks.append(WindowCheck(
        check_id="C8",
        check_name="Outcome availability",
        verdict=c8_verdict,
        actual=(
            f"{has_outcome}/{total_o} signals have ≥{horizon}D price bars for outcome computation. "
            f"Note: forward_signals.fwd_return_{horizon}d = NULL; outcomes computed from daily_prices."
        ),
        required=f"≥{horizon}D OHLC data available for outcome computation",
        note="Outcomes computed by V3ComparisonEngine from daily_prices, not forward_signals columns",
    ))
    if c8_verdict == CheckVerdict.FAIL:
        exclusion.append(f"C8: 0/{total_o} signals have {horizon}D outcomes")

    # ── C9: Duplicate signals ──────────────────────────────────────────────────
    cur.execute(
        f"""
        SELECT COUNT(*) - COUNT(DISTINCT stock_id || trade_date) as n_dups
        FROM forward_signals
        WHERE trade_signal IN ('buy','strong_buy')
        AND trade_date IN ({date_placeholders})
        """,
        signal_dates,
    )
    n_dups = cur.fetchone()[0]
    checks.append(WindowCheck(
        check_id="C9",
        check_name="Duplicate signals",
        verdict=CheckVerdict.PASS if n_dups == 0 else CheckVerdict.FAIL,
        actual=f"{n_dups} duplicate (stock_id, trade_date) pairs",
        required="Zero duplicates",
    ))

    # ── C10: Overlapping hold-period samples ──────────────────────────────────
    n_independent = len(signal_dates)
    effective_n_est = n_independent  # conservative: one per date
    c10_verdict = (
        CheckVerdict.PASS if n_independent >= 20
        else CheckVerdict.CONDITIONAL if n_independent >= 7
        else CheckVerdict.FAIL
    )
    checks.append(WindowCheck(
        check_id="C10",
        check_name="Overlapping hold-period samples",
        verdict=c10_verdict,
        actual=(
            f"{len(signal_dates)} trading dates. "
            f"Effective N (date-level clusters) ≈ {effective_n_est}. "
            f"Raw N = {total_sigs}. Bootstrap CI does NOT adjust for clustering."
        ),
        required=(
            "≥20 independent trading dates for minimally adequate inference. "
            "CI must be cluster-adjusted."
        ),
        note="STATISTICAL_CONFIDENCE_UNVERIFIED — CI will be reported without cluster adjustment",
    ))
    if c10_verdict == CheckVerdict.FAIL:
        exclusion.append(f"C10: Only {n_independent} independent dates < 7 minimum")

    # ── Determine overall verdict ──────────────────────────────────────────────
    n_fail = sum(1 for c in checks if c.verdict == CheckVerdict.FAIL)
    n_cond = sum(1 for c in checks if c.verdict == CheckVerdict.CONDITIONAL)

    if n_fail > 1 or eligible_sigs == 0:
        overall = WindowVerdict.INELIGIBLE
    elif n_fail == 1 or n_cond >= 4:
        overall = WindowVerdict.INELIGIBLE
    elif n_cond >= 2:
        overall = WindowVerdict.CONDITIONAL
    else:
        overall = WindowVerdict.ELIGIBLE

    # Regime check
    cur.execute(
        f"""
        SELECT market_regime_at_signal, COUNT(*)
        FROM forward_signals
        WHERE trade_signal IN ('buy','strong_buy')
        AND trade_date IN ({date_placeholders})
        AND is_valid=1 AND model_version='v8.0'
        GROUP BY market_regime_at_signal
        """,
        signal_dates,
    )
    regimes = dict(cur.fetchall())
    regime_str = "/".join(f"{k}={v}" for k, v in sorted(regimes.items()))
    regime_coverage = "single_regime" if len(regimes) == 1 else "multi_regime"

    return CandidateWindow(
        window_id=window_id,
        start_date=start,
        end_date=end,
        horizon_days=horizon,
        eligible_stock_count=len(set()),  # will be overridden below
        eligible_signal_count=eligible_sigs,
        paired_sample_count=has_outcome,
        missing_outcome_count=missing_o,
        universe_description=f"v8.0 buy/strong_buy signals, {start}–{end}, horizon={horizon}D",
        checks=checks,
        comparison_eligibility=overall,
        exclusion_reasons=exclusion,
        n_independent_dates=n_independent,
        effective_n_estimate=effective_n_est,
        benchmark_available=bench_ok,
        regime_coverage=regime_coverage + ":" + regime_str,
    )


def run_session40_window_discovery(conn: sqlite3.Connection) -> EligibleWindowDiscovery:
    """
    Discover eligible comparison windows from existing forward_signals data.

    Checks:
    - 5D horizon (available)
    - 10D horizon (insufficient post-bars)
    - 20D horizon (zero post-bars)

    Selection-bias prevention:
    - Windows assessed on DATA QUALITY only.
    - Performance NOT used for window selection.
    """
    discovery = EligibleWindowDiscovery()
    cur = conn.cursor()

    # Get all signal dates
    cur.execute(
        "SELECT DISTINCT trade_date FROM forward_signals "
        "WHERE trade_signal IN ('buy','strong_buy') ORDER BY trade_date"
    )
    all_dates = [r[0] for r in cur.fetchall()]

    # Candidate 1: All dates, 5D horizon
    w5d = _assess_window(conn, all_dates, horizon=5)
    w5d.eligible_stock_count = len({
        r[0] for r in conn.execute(
            "SELECT DISTINCT stock_id FROM forward_signals "
            "WHERE trade_signal IN ('buy','strong_buy')"
        ).fetchall()
    })
    discovery.candidate_windows.append(w5d)

    # Candidate 2: All dates, 10D horizon
    w10d = _assess_window(conn, all_dates, horizon=10)
    w10d.eligible_stock_count = w5d.eligible_stock_count
    discovery.candidate_windows.append(w10d)

    # Candidate 3: All dates, 20D horizon
    w20d = _assess_window(conn, all_dates, horizon=20)
    w20d.eligible_stock_count = w5d.eligible_stock_count
    discovery.candidate_windows.append(w20d)

    # Set overall verdict and best window
    conditional = discovery.conditional()
    eligible = discovery.eligible()

    if eligible:
        discovery.overall_verdict = "ELIGIBLE_WINDOW_FOUND"
        discovery.best_window_id = eligible[0].window_id
    elif conditional:
        discovery.overall_verdict = "CONDITIONAL_WINDOW_FOUND"
        discovery.best_window_id = conditional[0].window_id
    else:
        discovery.overall_verdict = "NO_ELIGIBLE_WINDOW"

    return discovery
