"""
scripts/run_research_backtest.py — Part E + F Research Validation Script

RESEARCH ONLY — NOT A PRODUCTION SYSTEM.

Performs a research backtest using:
  - Real historical DailyPrice OHLC from local SQLite (not Neon)
  - EntryTimingAnalyzer to generate research-only V2 shadow signals
  - EntryTimingExecutionSimulator for V1 and V2 OHLC simulation
  - Isolated SQLite research session (never touches production)

Data limitations:
  - Signal source: EntryTimingAnalyzer (NOT production ForwardSignal pipeline)
  - V1 baseline: same eligible signals, DIRECT_NEXT_OPEN (no scoring filter)
  - Local DailyPrice: 2024-07-01 to 2026-10-28, 721 stocks with ≥300 bars
  - Research period: 2026-04-01 to 2026-08-31 (safe 20D forward coverage)

REAL HISTORICAL PERFORMANCE — NOT VERIFIED against production ForwardSignal pipeline.
Results are based on real OHLC data but generated by research-only signal filter.
"""

from __future__ import annotations

import os
import sys
from collections import defaultdict
from datetime import date, timedelta
from typing import Dict, List

import pandas as pd
import sqlite3

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# ── Config ────────────────────────────────────────────────────────────────────

DB_PATH = os.path.join(os.path.dirname(os.path.dirname(__file__)), "data", "platform.db")

RESEARCH_PERIOD_START = date(2026, 4, 1)
RESEARCH_PERIOD_END   = date(2026, 8, 31)
MIN_BARS_HISTORY      = 60   # bars before signal date needed by EntryTimingAnalyzer
MIN_BARS_FORWARD      = 22   # minimum forward bars needed for 20D simulation
SAMPLE_STOCKS         = 100  # limit for performance; use all with ≥300 bars
EXPIRY_DAYS           = 10   # WAIT_FOR_* expiry window (trading days)
SIGNAL_STEP_DAYS      = 5    # check signals every N calendar days (weekly-ish)


def _load_ohlcv(conn: sqlite3.Connection, stock_id: str, start: date, end: date) -> pd.DataFrame:
    rows = conn.execute(
        "SELECT date, "
        "COALESCE(open, close) as open, "
        "close, "
        "COALESCE(high, close) as high, "
        "COALESCE(low, close) as low, "
        "COALESCE(volume, 0) as volume "
        "FROM daily_prices "
        "WHERE stock_id=? AND date BETWEEN ? AND ? "
        "ORDER BY date",
        (stock_id, str(start), str(end))
    ).fetchall()
    if not rows:
        return pd.DataFrame()
    df = pd.DataFrame(rows, columns=["date", "open", "close", "high", "low", "volume"])
    df["date"] = pd.to_datetime(df["date"]).dt.date
    for col in ["open", "close", "high", "low"]:
        df[col] = df[col].astype(float)
    return df


def _run_research_backtest() -> None:
    if not os.path.exists(DB_PATH):
        print(f"ERROR: Local SQLite not found at {DB_PATH}")
        print("Cannot run research backtest without local DailyPrice data.")
        return

    conn = sqlite3.connect(DB_PATH)

    # Select sample stocks with ≥300 bars in research period
    rows = conn.execute("""
        SELECT stock_id FROM daily_prices
        WHERE date BETWEEN '2024-07-01' AND '2026-09-15'
        GROUP BY stock_id HAVING COUNT(*) >= 300
        ORDER BY stock_id
        LIMIT ?
    """, (SAMPLE_STOCKS,)).fetchall()
    stock_ids = [r[0] for r in rows]
    print(f"=== Research Backtest ===")
    print(f"Period:  {RESEARCH_PERIOD_START} to {RESEARCH_PERIOD_END}")
    print(f"Stocks:  {len(stock_ids)} (of 721 eligible)")
    print(f"Source:  Local SQLite DailyPrice (real OHLC, NOT Neon)")
    print(f"Signals: EntryTimingAnalyzer (research-only, NOT production ForwardSignal)")
    print(f"WARNING: REAL HISTORICAL PERFORMANCE — NOT VERIFIED against production pipeline")
    print()

    from src.analyzers.entry_timing import EntryTimingAnalyzer
    from src.research.execution_simulator import (
        EntryTimingExecutionSimulator,
        STOP_BUFFER,
        _WAIT_PULLBACK_LABEL,
    )

    analyzer = EntryTimingAnalyzer()
    sim = EntryTimingExecutionSimulator()

    # ── Generate research signals ─────────────────────────────────────────────
    research_signals = []
    signal_date = RESEARCH_PERIOD_START
    while signal_date <= RESEARCH_PERIOD_END:
        for stock_id in stock_ids:
            # Load history up to and including signal_date
            hist_start = signal_date - timedelta(days=MIN_BARS_HISTORY * 2)
            hist = _load_ohlcv(conn, stock_id, hist_start, signal_date)
            if len(hist) < 21:
                continue

            result = analyzer.analyze(stock_id, hist)
            if result.entry_label not in (
                "ENTRY_READY", "WAIT_FOR_PULLBACK", "WAIT_FOR_BREAKOUT"
            ):
                continue
            if result.stop_price is None or result.target_price is None:
                continue

            research_signals.append({
                "signal_date": signal_date,
                "stock_id": stock_id,
                "entry_label": result.entry_label,
                "entry_price": result.entry_price,
                "stop_price": result.stop_price,
                "target_price": result.target_price,
                "prior_20d_high": result.prior_20d_high,
                "ma20": result.ma20,
            })

        signal_date += timedelta(days=SIGNAL_STEP_DAYS)

    print(f"Research signals generated: {len(research_signals)}")
    if not research_signals:
        print("No signals generated — check data or analyzer settings.")
        conn.close()
        return

    # ── Dedup: same stock within 28 days ─────────────────────────────────────
    seen: Dict[str, date] = {}
    deduped = []
    for sig in sorted(research_signals, key=lambda x: x["signal_date"]):
        last = seen.get(sig["stock_id"])
        if last is None or (sig["signal_date"] - last).days > 28:
            deduped.append(sig)
            seen[sig["stock_id"]] = sig["signal_date"]
    print(f"After 28-day dedup: {len(deduped)} signals (removed {len(research_signals)-len(deduped)})")
    print()

    # ── Simulate V1 and V2 ────────────────────────────────────────────────────
    label_counts: Dict[str, int] = defaultdict(int)
    v1_fos_rets: List[float] = []
    v2_fos_rets: List[float] = []
    v2_filled_rets: List[float] = []
    no_fill_v1_rets: List[float] = []
    paired_deltas: List[float] = []
    wait_days: List[float] = []
    missing_fwd = 0

    stop_hits_v1 = target_hits_v1 = 0
    stop_hits_v2 = target_hits_v2 = 0
    mae_v1: List[float] = []
    mfe_v1: List[float] = []
    mae_v2: List[float] = []
    mfe_v2: List[float] = []

    for sig in deduped:
        label_counts[sig["entry_label"]] += 1
        signal_date = sig["signal_date"]

        # Load full OHLCV (pre + post signal)
        fwd_end = signal_date + timedelta(days=50)
        ohlcv = _load_ohlcv(conn, sig["stock_id"],
                             signal_date - timedelta(days=5), fwd_end)
        if ohlcv.empty:
            missing_fwd += 1
            continue

        # Check forward data adequacy
        post_bars = ohlcv[ohlcv["date"] > signal_date]
        if len(post_bars) < MIN_BARS_FORWARD:
            missing_fwd += 1
            continue

        stop_price  = float(sig["stop_price"])
        target_price = float(sig["target_price"])

        # ── V1 simulation (DIRECT_NEXT_OPEN) ─────────────────────────────
        v1_trade = sim.simulate_v1(
            signal_date=signal_date,
            stock_id=sig["stock_id"],
            stop_price=stop_price,
            target_price=target_price,
            ohlcv=ohlcv,
        )
        # Skip if target_price ≤ fill_price (gap-up overnight makes trade incoherent)
        if (v1_trade.filled and v1_trade.fill_price and
                v1_trade.fill_price >= float(sig["target_price"])):
            missing_fwd += 1  # count as unusable
            continue

        v1_ret = v1_trade.net_return_pct if v1_trade.net_return_pct is not None else 0.0
        v1_fos_rets.append(v1_ret)
        if v1_trade.stop_hit:   stop_hits_v1 += 1
        if v1_trade.target_hit: target_hits_v1 += 1
        if v1_trade.mae_pct is not None: mae_v1.append(v1_trade.mae_pct)
        if v1_trade.mfe_pct is not None: mfe_v1.append(v1_trade.mfe_pct)

        # ── V2 simulation (conditional entry) ────────────────────────────
        # SA-1 fix: for WAIT_FOR_PULLBACK, use MA20_estimate as planned_entry
        if sig["entry_label"] == _WAIT_PULLBACK_LABEL:
            planned_entry = stop_price / (1.0 - STOP_BUFFER)
        else:
            planned_entry = float(sig["entry_price"]) if sig["entry_price"] else 100.0

        v2_trade = sim.simulate_v2(
            signal_date=signal_date,
            stock_id=sig["stock_id"],
            entry_label=sig["entry_label"],
            planned_entry=planned_entry,
            stop_price=stop_price,
            target_price=target_price,
            ohlcv=ohlcv,
            prior_20d_high=float(sig["prior_20d_high"]) if sig["prior_20d_high"] else None,
            expiry_days=EXPIRY_DAYS,
        )

        if v2_trade.filled and v2_trade.net_return_pct is not None:
            v2_ret = v2_trade.net_return_pct
            v2_filled_rets.append(v2_ret)
            v2_fos_rets.append(v2_ret)
            wait_days.append(float(v2_trade.waiting_days))
            if v2_trade.stop_hit:   stop_hits_v2 += 1
            if v2_trade.target_hit: target_hits_v2 += 1
            if v2_trade.mae_pct is not None: mae_v2.append(v2_trade.mae_pct)
            if v2_trade.mfe_pct is not None: mfe_v2.append(v2_trade.mfe_pct)
        else:
            v2_ret = 0.0  # SA-7
            v2_fos_rets.append(0.0)
            no_fill_v1_rets.append(v1_ret)

        paired_deltas.append(v2_ret - v1_ret)

    conn.close()

    # ── Compute statistics ────────────────────────────────────────────────────
    # net_return_pct is already in % form (e.g. 5.3 = 5.3%) — do NOT multiply by 100
    def _mean(lst): return round(sum(lst) / len(lst), 2) if lst else None
    def _win_rate(lst): return round(sum(1 for r in lst if r > 0) / len(lst) * 100, 1) if lst else None
    def _n(lst): return len(lst)

    n_eligible = len(v1_fos_rets)
    n_fillable = len(v2_fos_rets)
    n_filled   = len(v2_filled_rets)
    n_no_fill  = len(v2_fos_rets) - n_filled
    fill_rate  = round(n_filled / max(n_fillable, 1) * 100, 1) if n_fillable else None
    avg_wait   = round(sum(wait_days) / len(wait_days), 1) if wait_days else None
    perf_delta = round(sum(paired_deltas) / len(paired_deltas) * 100, 2) if paired_deltas else None

    # Missed opportunity
    pos_missed = [r for r in no_fill_v1_rets if r > 0]
    neg_missed = [r for r in no_fill_v1_rets if r < 0]

    # ── Print report ──────────────────────────────────────────────────────────
    INSUFFICIENT = n_eligible < 30

    if INSUFFICIENT:
        print("⚠ INSUFFICIENT SAMPLE (n < 30) — results not statistically reliable")
    else:
        print("Sample size adequate for preliminary analysis (n ≥ 30)")
    print()

    print("── Signal Distribution ───────────────────────────────────")
    for lbl, cnt in sorted(label_counts.items()):
        print(f"  {lbl:<25}: {cnt}")
    print(f"  {'MISSING_FWD_DATA':<25}: {missing_fwd}")
    print()

    print("── Performance Summary ─────────────────────────────────────")
    header = f"{'Metric':<30}  {'V1 (DIRECT)':<14}  {'V2 (FOS)':<14}"
    print(header)
    print("-" * len(header))

    def _fmt(val):
        return f"{val:+.2f}%" if val is not None else "N/A"

    rows_data = [
        ("Eligible Signals (N)",    n_eligible,                  n_fillable),
        ("Filled Trades",           n_eligible,                  n_filled),
        ("Fill Rate",               "100%",                      f"{fill_rate}%" if fill_rate else "N/A"),
        ("Avg Waiting Days",        "0 (immediate)",             f"{avg_wait}d" if avg_wait else "N/A"),
        ("Net Return (20D) Mean",   _fmt(_mean(v1_fos_rets)),    _fmt(_mean(v2_fos_rets))),
        ("Win Rate",                f"{_win_rate(v1_fos_rets)}%" if _win_rate(v1_fos_rets) else "N/A",
                                    f"{_win_rate(v2_fos_rets)}%" if _win_rate(v2_fos_rets) else "N/A"),
        ("Stop Hit Rate",           f"{stop_hits_v1}/{n_eligible}",    f"{stop_hits_v2}/{n_filled}"),
        ("Target Hit Rate",         f"{target_hits_v1}/{n_eligible}",  f"{target_hits_v2}/{n_filled}"),
        ("Avg MAE",                 _fmt(_mean(mae_v1)),         _fmt(_mean(mae_v2))),
        ("Avg MFE",                 _fmt(_mean(mfe_v1)),         _fmt(_mean(mfe_v2))),
    ]
    for name, v1_val, v2_val in rows_data:
        print(f"  {name:<30}  {str(v1_val):<14}  {str(v2_val):<14}")

    print()
    print("── Performance Delta & Missed Opportunity ──────────────────")
    print(f"  Performance Delta (mean paired V2-V1): {_fmt(perf_delta)}")
    if no_fill_v1_rets:
        smr = _mean(no_fill_v1_rets)
        pmu = _mean(pos_missed) if pos_missed else None
        al  = _mean(neg_missed) if neg_missed else None
        print(f"  Missed Opportunity signals (n): {len(no_fill_v1_rets)}")
        print(f"    Signed Missed Return (mean V1 for no-fill V2): {_fmt(smr)}")
        print(f"    Positive Missed Upside (V1>0 cases): {_fmt(pmu)} (n={len(pos_missed)})")
        print(f"    Avoided Loss (V1<0 cases): {_fmt(al)} (n={len(neg_missed)})")
    else:
        print("  No no-fill signals in this run.")

    print()
    print("── Data & Methodology Notes ────────────────────────────────")
    print("  [1] REAL HISTORICAL PERFORMANCE — NOT VERIFIED against production ForwardSignal pipeline")
    print("  [2] Signal source: EntryTimingAnalyzer (research-only, not v8.0 scoring)")
    print("  [3] V1 uses same stop/target as V2 (MA20-based, same signal_date info)")
    print("  [4] Uses real DailyPrice open column (COALESCE(open, close) from local SQLite)")
    print("  [5] SA-1: WAIT_FOR_PULLBACK trigger = stop/(1-0.03)×1.03; CONFIRMED_NEXT_OPEN")
    print("  [6] SA-7: V2 no-fill → 0% in FOS")
    print("  [7] Dedup: 28-calendar-day window per stock")
    if INSUFFICIENT:
        print("  [8] INSUFFICIENT SAMPLE — do not make strategy decisions from these results")
    print()
    print(f"Research VERDICT: ", end="")
    if INSUFFICIENT:
        print("CONDITIONAL — insufficient sample for statistical significance")
    elif perf_delta is not None and abs(perf_delta) < 0.1:
        print("CONDITIONAL — performance delta within noise, need larger sample")
    elif perf_delta is not None and perf_delta > 0:
        print("CONDITIONAL — V2 appears favorable but requires out-of-sample validation")
    else:
        print("CONDITIONAL — further analysis required")


if __name__ == "__main__":
    _run_research_backtest()
